import test from 'node:test';
import assert from 'node:assert/strict';
import { PLUGIN_FILES } from './pluginFiles';

test('PLUGIN_FILES contains required WordPress metadata and all architectural classes', () => {
  const mainFile = PLUGIN_FILES.find((f) => f.path === 'oscarpx-backup-restore.php');
  assert.ok(mainFile, 'Main plugin file must exist');
  assert.match(mainFile.content, /Plugin Name:\s+OscarPx Backup & Restore/);
  assert.match(mainFile.content, /Author:\s+OscarPx/);
  assert.match(mainFile.content, /Author URI:\s+https:\/\/oscarpx\.com/);
  assert.match(mainFile.content, /Version:\s+1\.0\.0/);

  const securityFile = PLUGIN_FILES.find((f) => f.path === 'includes/class-oscarpx-security.php');
  assert.ok(securityFile);
  assert.match(securityFile.content, /check_ajax_referer/);
  assert.match(securityFile.content, /manage_options/);
  assert.match(securityFile.content, /Deny from all/);
  assert.match(securityFile.content, /index\.php/);
  assert.match(securityFile.content, /ob_end_clean/);
  assert.match(securityFile.content, /job\.json/);
  assert.match(securityFile.content, /enable_maintenance_mode/);
  assert.match(securityFile.content, /disable_maintenance_mode/);
  assert.match(securityFile.content, /\.maintenance/);
  assert.match(securityFile.content, /wp_maintenance/);
  assert.match(securityFile.content, /build_backup_filename/);
  assert.match(securityFile.content, /get_bloginfo\(\s*'name'\s*\)/);
  assert.match(securityFile.content, /sanitize_title/);
  assert.match(securityFile.content, /date\(\s*'Y-m-d_H-i-s'\s*\)/);

  const dbFile = PLUGIN_FILES.find((f) => f.path === 'includes/class-oscarpx-db-engine.php');
  assert.ok(dbFile);
  assert.match(dbFile.content, /global \$wpdb/);
  assert.equal(dbFile.content.includes('mysqldump'), false);

  const restoreFile = PLUGIN_FILES.find((f) => f.path === 'includes/class-oscarpx-restore-engine.php');
  assert.ok(restoreFile);
  assert.match(restoreFile.content, /stage\//);
  assert.match(restoreFile.content, /suppress_errors\(\s*true\s*\)/);
  assert.match(restoreFile.content, /apply_stage_chunk/);
  assert.match(restoreFile.content, /is_protected_core_file/);
  assert.match(restoreFile.content, /wp-config\.php/);
  assert.match(restoreFile.content, /\.htaccess/);
  assert.equal(restoreFile.content.includes('apply_wp_config_safely'), false);
  assert.match(restoreFile.content, /is_allowed_restore_sql/);
  assert.match(restoreFile.content, /DROP DATABASE/);
  assert.match(restoreFile.content, /CREATE DATABASE/);
  assert.match(restoreFile.content, /\$wpdb->flush\(\)/);
  assert.match(restoreFile.content, /search_replace_chunk/);

  const adminPhp = PLUGIN_FILES.find((f) => f.path === 'includes/class-oscarpx-admin.php');
  assert.ok(adminPhp);
  assert.match(adminPhp.content, /OscarPx_Security::enable_maintenance_mode/);
  assert.match(adminPhp.content, /ajax_process_search_replace_chunk/);
  assert.match(adminPhp.content, /OscarPx_Security::disable_maintenance_mode/);
  assert.match(adminPhp.content, /Gestor de Backups/);
  assert.match(adminPhp.content, /scandir/);
  assert.match(adminPhp.content, /ajax_upload_backup_chunk/);
  assert.match(adminPhp.content, /sanitize_file_name/);
  assert.match(adminPhp.content, /realpath/);
  assert.match(adminPhp.content, /unlink/);
  assert.match(adminPhp.content, /admin_post_download_oscarpx_backup/);
  assert.match(adminPhp.content, /handle_download_backup/);
  assert.match(adminPhp.content, /wp_verify_nonce/);
  assert.match(adminPhp.content, /Content-Type: application\/zip/);
  assert.match(adminPhp.content, /Content-Disposition: attachment/);
  assert.match(adminPhp.content, /Content-Length:/);
  assert.match(adminPhp.content, /ob_clean\(\)/);
  assert.match(adminPhp.content, /flush\(\)/);
  assert.match(adminPhp.content, /fread\(\s*\$handle/);
  assert.match(adminPhp.content, /oscarpx-backup-type/);
  assert.match(adminPhp.content, /PARENT_MENU_SLUG\s*=\s*'px-tools'/);
  assert.match(adminPhp.content, /\$admin_page_hooks\[\s*self::PARENT_MENU_SLUG\s*\]/);
  assert.match(adminPhp.content, /add_menu_page\(/);
  assert.match(adminPhp.content, /'PX Tools'/);
  assert.match(adminPhp.content, /'dashicons-superhero'/);
  assert.match(adminPhp.content, /add_submenu_page\(\s*self::PARENT_MENU_SLUG/);
  assert.match(adminPhp.content, /remove_submenu_page\(\s*self::PARENT_MENU_SLUG/);
  assert.match(adminPhp.content, /px-tools_page_/);
  assert.equal(adminPhp.content.includes("'toplevel_page_' . self::MENU_SLUG"), false);
  const downloadFnStart = adminPhp.content.indexOf('function handle_download_backup');
  assert.ok(downloadFnStart !== -1);
  const downloadFnBody = adminPhp.content.slice(downloadFnStart);
  assert.equal(downloadFnBody.includes('file_get_contents'), false);
  assert.match(downloadFnBody, /exit;/);

  const adminJs = PLUGIN_FILES.find((f) => f.path === 'assets/js/oscarpx-admin.js');
  assert.ok(adminJs);
  assert.match(adminJs.content, /res\.text\(\)/);
  assert.match(adminJs.content, /oscarpx_process_apply_chunk/);
  assert.match(adminJs.content, /oscarpx_process_search_replace_chunk/);
  assert.match(adminJs.content, /oscarpx_maint_key/);
  assert.match(adminJs.content, /file\.slice\(/);
  assert.match(adminJs.content, /oscarpx_upload_backup_chunk/);
  assert.match(adminJs.content, /oscarpx_delete_backup/);
  assert.match(adminJs.content, /oscarpx-backup-type/);
  assert.match(adminJs.content, /download_url/);
  assert.equal(adminJs.content.includes('window.location.reload'), false);
});

